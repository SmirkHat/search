#!/usr/bin/env node
/**
 * Read public/bangs-hot.json → shared/bangs-hot.generated.ts (inlined for Edge/SW).
 * Usage: node scripts/generate-hot-module.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const hotPath = join(root, "public", "bangs-hot.json");
const outPath = join(root, "shared", "bangs-hot.generated.ts");

function main() {
  const raw = JSON.parse(readFileSync(hotPath, "utf8"));
  if (!Array.isArray(raw)) {
    throw new Error("bangs-hot.json must be an array");
  }

  const rows = [];
  for (const item of raw) {
    if (!item || typeof item !== "object") continue;
    const t = String(item.t ?? "")
      .trim()
      .toLowerCase();
    const u = String(item.u ?? "").trim();
    if (!t || !u) continue;
    rows.push({ t, u });
  }

  const body = `/* Auto-generated by scripts/generate-hot-module.mjs — do not edit. */
import type { CompactBang } from "./bang-compact";

export const HOT_BANGS: readonly CompactBang[] = ${JSON.stringify(rows)};

export const HOT_BANG_COUNT = ${rows.length} as const;
`;

  writeFileSync(outPath, body);
  console.log(
    `Wrote ${rows.length} inlined hot bangs → ${outPath} (${(Buffer.byteLength(body) / 1024).toFixed(1)} KB)`,
  );
}

main();
